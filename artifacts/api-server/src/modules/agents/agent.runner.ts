export interface RunAgentOptions {
  campaignId: string | null | undefined;
  workspaceId: string;
  agentRole: AgentRole;
  systemPrompt: string;
  messages: AIMessage[];
  log: Logger;
  requiresApproval?: boolean;
  checkpointType?: string;
  thinkingMessages?: string[];
  /** Campaign Memory Layer context — injected before system prompt when provided. */
  memoryContext?: string;
  /**
   * Psychological Profile block — formatted output of buildPsychologicalProfileBlock().
   * Injected between the memory layer and the agent-specific system prompt.
   * Provides the 6-map avatar synthesis (linguagem, desejo, objeção, identidade, emoção, mercado)
   * so every agent operates with full psychological context, not just raw intake fields.
   */
  profileContext?: string;
  /**
   * Dynamic Avatar State block — phase-specific emotional state for this content piece.
   * Generated by buildPhaseStateBlock() (single phase) or buildArcOverviewBlock() (all phases).
   * Injected between the psychological profile and the agent system prompt.
   * Tells the agent exactly WHERE in the funnel the avatar is right now — belief level,
   * resistance, dominant emotion, voice fragment, and copy directives for this phase only.
   */
  phaseContext?: string;
}

export interface RunAgentResult {
  agentRecord: CampaignAgent;
  content: string;
  creditsCharged: number;
  checkpointId?: string;
}

