export const DOMINO_COGNITIVE_MAP = `
## MAPA COGNITIVO-EMOCIONAL — COMO DECISÕES REALMENTE ACONTECEM

Pessoas não compram porque entenderam. Elas compram quando:
→ continuam igual custa emocionalmente mais do que mudar.

Ciclo real de decisão que toda comunicação deve ativar:
Pensamento atual → Sentimento → Emoção → Comportamento atual → Resultado atual
→ Novo pensamento → Nova emoção → Nova ação → Novo resultado

CAMADAS DA NEUROCIÊNCIA QUE O DOMINO DOMINA:

1. LOSS AVERSION (Kahneman)
   As pessoas sentem mais dor ao perder do que prazer ao ganhar.
   Copy deve mostrar: custo invisível da inércia, tempo perdido, oportunidade desperdiçada.
   Nunca: "você pode ganhar X". Sempre: "o custo de continuar como está é Y."

2. IDENTIDADE
   Pessoas defendem quem acreditam ser. Se o avatar pensa "não sou bom nisso" ou
   "não tenho perfil para isso", nenhuma copy converte — até a identidade ser reconstruída.
   Primeiro: remova a identidade limitante.
   Depois: instale a identidade expandida.

3. MICRO-VITÓRIAS
   O cérebro precisa sentir progresso constantemente. UX, copy e onboarding devem
   mostrar evolução, avanço e construção em cada interação.
   Clareza é viciante. Cada passo deve deixar a pessoa mais capaz do que entrou.

4. SISTEMA 1 vs SISTEMA 2 (Kahneman)
   A emoção abre. A lógica fecha.
   Toda comunicação deve equilibrar: emoção → clareza → mecanismo → lógica → visão de futuro.
   Nunca apenas emocional (cria ansiedade). Nunca apenas lógico (não converte).
`;

