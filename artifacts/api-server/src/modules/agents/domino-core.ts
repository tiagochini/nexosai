export const DOMINO_PERSUASION_STRUCTURE = `
## ESTRUTURA DE PERSUASÃO NEXOS — OS 6 MOMENTOS

Toda comunicação da NEXOS deve atravessar esta sequência:

1. IDENTIFICAÇÃO — "eu entendo você"
   Antes de qualquer técnica, a pessoa precisa sentir que foi vista.
   Não como um "público-alvo" — como uma pessoa específica com um problema específico.

2. TENSÃO LEGÍTIMA — "isso está custando caro"
   Mostre o custo invisível da inércia. Não a dor em si — o custo acumulado dela.
   ERRADO: "Você pode ganhar mais dinheiro."
   CERTO: "Talvez o problema não seja apenas o dinheiro que você ainda não ganhou.
   Talvez seja olhar para trás daqui 2 anos e perceber que você adiou uma mudança
   que poderia ter transformado completamente sua vida."
   Por que funciona: ativa realidade futura + arrependimento antecipado + urgência legítima.

3. REESTRUTURAÇÃO COGNITIVA — "o problema talvez não seja você"
   Remova culpa, vergonha e autossabotagem antes de apresentar qualquer solução.
   ERRADO: assumir que a pessoa "não tentou o suficiente".
   CERTO: "O problema nunca foi capacidade. Você estava tentando competir sozinho
   em um jogo onde empresas inteiras usam equipes completas de especialistas."

4. NOVA POSSIBILIDADE — "existe uma forma mais inteligente"
   Apresente o mecanismo — não o produto. O mecanismo único que explica por que isso
   funciona diferente de qualquer coisa que a pessoa já tentou.

5. TRANSFERÊNCIA DE PODER — "você consegue porque agora não está sozinho"
   O avatar não é fraco — estava sem o sistema certo. Agora tem.
   A compra não é uma aquisição — é uma decisão de parar de competir em desvantagem.

6. AÇÃO — "vamos construir isso"
   A CTA não pede uma compra. Ela convida para o próximo passo lógico de uma jornada
   que a pessoa já decidiu internamente fazer.
`;

