export type Translations = typeof TRANSLATIONS["pt-BR"];

interface LangContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Translations;
}

const LangContext = createContext<LangContextType>({
  lang: "pt-BR",
  setLang: () => {},
  t: TRANSLATIONS["pt-BR"],
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem("nexos_lang") as Lang | null;
    if (stored && stored in TRANSLATIONS) return stored;
    const browser = navigator.language;
    if (browser.startsWith("es")) return "es-LA";
    if (browser.startsWith("en")) return "en-US";
    return "pt-BR";
  });

  const setLang = (l: Lang) => {
    localStorage.setItem("nexos_lang", l);
    setLangState(l);
  };

  const t = TRANSLATIONS[lang] ?? TRANSLATIONS["pt-BR"];

  return (
    <LangContext.Provider value={{ lang, setLang, t: t as Translations }}>
      {children}
    </LangContext.Provider>
  );
}

export function useI18n() {
  return useContext(LangContext);
}
